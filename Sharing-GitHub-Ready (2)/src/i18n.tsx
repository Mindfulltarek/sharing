export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try { return window.localStorage.getItem('sharing.language.v1') === 'ar' ? 'ar' : 'en'; } catch { return 'en'; }
  });
  useLayoutEffect(() => {
    const isArabic = language === 'ar';
    try { window.localStorage.setItem('sharing.language.v1', language); } catch { /* Language preference is optional. */ }
    document.documentElement.lang = isArabic ? 'ar' : 'en';
    document.documentElement.dir = isArabic ? 'rtl' : 'ltr';
  }, [language]);
  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (english: string, values?: Record<string, string | number>) => {
      const translated = language === 'ar' ? ar[english] || english : english;
      return translated.replace(/\{(\w+)\}/g, (match, key: string) => values?.[key] === undefined ? match : String(values[key]));
    },
  }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}

export function LanguageToggle({ className = '' }: { className?: string }) {
  const { language, setLanguage } = useLanguage();
  const next = language === 'en' ? 'ar' : 'en';
  return <button type="button" className={`language-toggle ${className}`} onClick={() => setLanguage(next)} aria-label={language === 'en' ? 'Switch language to Arabic' : 'بدّل اللغة إلى الإنجليزية'} title={language === 'en' ? 'العربية' : 'English'}>{language.toUpperCase()}</button>;
}
